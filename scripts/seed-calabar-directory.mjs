async function seedCalabarDirectory() {
  console.log('--- Seeding/Enriching Calabar Directory ---');
  let createdCount = 0;
  let updatedCount = 0;

  for (const item of CALABAR_DIRECTORY_DATA) {
    // Check if listing already exists by slug
    const existingListing = await db.orm.public.DiscoveryListing
      .where({ slug: item.slug })
      .all()
      .first();

    const metadata = JSON.stringify({
      phone: item.phone || null,
      whatsapp: item.whatsapp || null,
      hours: item.hours,
      zone: item.zone,
      landmark: item.landmark,
      category: item.directoryCategory,
      directoryCategory: item.directoryCategory,
      services: item.services,
      claimed: false,
      verified: false,
      coverImage: item.coverImage || null,
      address: item.address,
      description: item.description,
      rating: 4.8 + Math.round(Math.random() * 2) / 10,
    });

    if (existingListing) {
      // Update metadata and ensure active
      await db.orm.public.DiscoveryListing
        .where({ id: existingListing.id })
        .update({
          isActive: true,
          metadata,
          coverAssetId: item.coverImage || null,
          description: item.description,
          title: item.name,
        });

      // Update organization if present
      if (existingListing.organizationId) {
        await db.orm.public.Organization
          .where({ id: existingListing.organizationId })
          .update({
            name: item.name,
            address: item.address,
            description: item.description,
            storeCategory: item.storeCategory,
          });
      }
      updatedCount++;
    } else {
      // Create new organization and listing
      const orgId = uuidv4();
      await db.orm.public.Organization.create({
        id: orgId,
        name: item.name,
        type: item.type,
        storeCategory: item.storeCategory,
        address: item.address,
        description: item.description,
        status: 'ACTIVE',
      });

      await db.orm.public.DiscoveryListing.create({
        id: uuidv4(),
        organizationId: orgId,
        cityId: CALABAR_CITY_ID,
        vertical: item.type,
        slug: item.slug,
        title: item.name,
        description: item.description,
        coverAssetId: item.coverImage || null,
        isActive: true,
        metadata,
      });
      createdCount++;
    }
  }

  console.log(`Directory Seeding Complete: ${createdCount} created, ${updatedCount} updated.`);
}

seedCalabarDirectory()
  .then(() => process.exit(0))
  .catch((err) => {
    console.error('Error seeding directory:', err);
    process.exit(1);
  });
